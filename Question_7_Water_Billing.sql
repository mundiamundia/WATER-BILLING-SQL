CREATE OR REPLACE FUNCTION trg_reading_validate_fn()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.current_reading<NEW.previous_reading THEN RAISE EXCEPTION 'Current reading cannot be below previous reading'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER trg_reading_validate BEFORE INSERT OR UPDATE ON readings
FOR EACH ROW EXECUTE FUNCTION trg_reading_validate_fn();

