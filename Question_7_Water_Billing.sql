CREATE OR REPLACE FUNCTION fn_water_charge(p_units numeric)
RETURNS numeric(12,2) LANGUAGE plpgsql AS $$
BEGIN
 IF p_units IS NULL OR p_units<0 THEN RAISE EXCEPTION 'Consumption must be non-negative and not NULL'; END IF;
 RETURN (LEAST(p_units,10)*5 + GREATEST(p_units-10,0)*8)::numeric(12,2);
END $$;

CREATE OR REPLACE PROCEDURE pr_generate_bill(p_reading_id integer,p_due_on date)
LANGUAGE plpgsql AS $$
DECLARE v_prev numeric(12,2); v_curr numeric(12,2);
BEGIN
 IF p_due_on IS NULL THEN RAISE EXCEPTION 'Due date is required'; END IF;
 SELECT previous_reading,current_reading INTO v_prev,v_curr FROM readings WHERE reading_id=p_reading_id;
 IF NOT FOUND THEN RAISE EXCEPTION 'Unknown reading ID %',p_reading_id; END IF;
 IF EXISTS(SELECT 1 FROM bills WHERE reading_id=p_reading_id) THEN RAISE EXCEPTION 'A bill already exists for this reading'; END IF;
 INSERT INTO bills(reading_id,charge,amount_paid,due_on)
 VALUES(p_reading_id,fn_water_charge(v_curr-v_prev),0,p_due_on);
END $$;
CALL pr_generate_bill(1,CURRENT_DATE+14);
CALL pr_generate_bill(2,CURRENT_DATE-2);
CALL pr_generate_bill(3,CURRENT_DATE-1);
CALL pr_generate_bill(4,CURRENT_DATE+10);
CALL pr_generate_bill(5,CURRENT_DATE-3);
CALL pr_generate_bill(6,CURRENT_DATE+7);
UPDATE bills SET amount_paid=10 WHERE reading_id=3;

CREATE OR REPLACE VIEW v_overdue_bills AS
SELECT c.full_name,b.due_on,(b.charge-b.amount_paid)::numeric(12,2) AS outstanding_amount
FROM bills b JOIN readings r USING(reading_id) JOIN customers c USING(customer_id)
WHERE b.due_on<CURRENT_DATE AND b.amount_paid<b.charge;
SELECT * FROM v_overdue_bills;

CREATE INDEX idx_bills_due_on ON bills(due_on);
EXPLAIN SELECT bill_id,reading_id,charge-amount_paid AS outstanding
FROM bills WHERE due_on<CURRENT_DATE AND amount_paid<charge;

CREATE OR REPLACE PROCEDURE pr_refresh_receivables()
LANGUAGE plpgsql AS $$
BEGIN
 INSERT INTO receivable_snapshot(snapshot_date,total_due)
 SELECT CURRENT_DATE,COALESCE(SUM(charge-amount_paid),0) FROM bills
 ON CONFLICT(snapshot_date) DO UPDATE SET total_due=EXCLUDED.total_due;
END $$;
CALL pr_refresh_receivables();

